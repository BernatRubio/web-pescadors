export function t(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  let text: string = ui[locale][key];
  for (const [name, value] of Object.entries(vars ?? {})) {
    text = text.replace(`{${name}}`, String(value));
  }
  return text;
}
